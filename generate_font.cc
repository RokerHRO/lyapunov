#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <stdexcept>
#include <string>
#include <vector>

namespace
{

constexpr int first_char  = 0x20;
constexpr int last_char   = 0x7f;
constexpr int glyph_count = last_char - first_char + 1; // 96

struct FontData
{
	unsigned width;  // in pixel
	unsigned height; // in pixel
	std::vector<uint16_t> rows; // glyph_count * height rows, MSB-first, glyph in the top `width` bits
};

std::vector<unsigned char> read_file(const std::string& path)
{
	std::ifstream in(path, std::ios::binary);
	if (!in)
		throw std::invalid_argument("cannot open " + path);
	return { std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>() };
}

void write_file(const std::string& path, const std::string& data)
{
	std::ofstream out(path, std::ios::binary);
	if (!out)
		throw std::invalid_argument("cannot open " + path + " for writing");
	out << data;
	if (!out)
		throw std::invalid_argument("cannot write " + path);
}

uint32_t u32le(const unsigned char* d)
{
	return uint32_t(d[0]) | uint32_t(d[1]) << 8 | uint32_t(d[2]) << 16 | uint32_t(d[3]) << 24;
}

std::string hex16(unsigned v)
{
	char buf[8];
	snprintf(buf, sizeof(buf), "0x%04X", v);
	return buf;
}

// file name without directory and extension
std::string stem(const std::string& path)
{
	std::string s = path;
	const auto slash = s.find_last_of("/\\");
	if (slash != std::string::npos)
		s.erase(0, slash + 1);
	const auto dot = s.find_last_of('.');
	if (dot != std::string::npos)
		s.erase(dot);
	return s;
}

std::string identifier(const std::string& s)
{
	std::string id = s;
	for (char& ch : id)
		if (!((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') || ch == '_'))
			ch = '_';
	if (id.empty() || (id[0] >= '0' && id[0] <= '9'))
		id = "_" + id;
	return id;
}

// PSF1 (magic 0x0436): 4-byte header, then 256 glyphs of 16 bytes each
// (16 rows x 8 pixel, one MSB-first byte per row)
FontData convert_psf1(const std::vector<unsigned char>& data)
{
	if (data.size() < 4 || data[0] != 0x36 || data[1] != 0x04)
		throw std::invalid_argument("invalid PSF1 format");
	if (data[3] != 16)
		throw std::invalid_argument("unexpected glyph size");

	const size_t offset = 4 + first_char * data[3];
	if (data.size() < offset + size_t(glyph_count) * data[3])
		throw std::invalid_argument("incomplete glyph data");

	FontData font;
	font.width = 8;
	font.height = 16;
	font.rows.resize(size_t(glyph_count) * font.height);
	for (int i = 0; i < glyph_count; ++i)
		for (unsigned y = 0; y < font.height; ++y)
			font.rows[size_t(i) * font.height + y] = uint16_t(data[offset + size_t(i) * font.height + y]);
	return font;
}

// PSF2 (magic 0x864AB572): 32-byte header, then `numglyph` glyphs of
// `bytesperglyph` bytes each, packed sequentially (no bitmap offset table)
FontData convert_psf2(const std::vector<unsigned char>& data)
{
	if (data.size() < 32)
		throw std::invalid_argument("file too small for PSF2 header");

	const uint32_t headersize    = u32le(&data[8]);
	const uint32_t numglyph      = u32le(&data[16]);
	const uint32_t bytesperglyph = u32le(&data[20]);
	const uint32_t height        = u32le(&data[24]);
	const uint32_t width         = u32le(&data[28]);

	if (width < 1 || width > 16)
		throw std::invalid_argument("uint16_t supports a maximum width of 16 pixels, found " + std::to_string(width));
	if (height < 1)
		throw std::invalid_argument("invalid glyph height");
	if (numglyph <= last_char)
		throw std::invalid_argument("font does not contain enough glyphs");

	const size_t bytes_per_row = (width + 7) / 8;
	const size_t required_bytes = bytes_per_row * height;
	if (bytesperglyph < required_bytes)
		throw std::invalid_argument("glyph size in header is too small");
	if (data.size() < headersize + size_t(numglyph) * bytesperglyph)
		throw std::invalid_argument("incomplete glyph data");

	FontData font;
	font.width = width;
	font.height = height;
	font.rows.resize(size_t(glyph_count) * height);
	for (int c = first_char; c <= last_char; ++c)
	{
		const unsigned char* glyph = &data[headersize + size_t(c) * bytesperglyph];
		for (size_t y = 0; y < height; ++y)
		{
			// row is stored MSB-first; the shift keeps the glyph in the top `width` bits
			unsigned value = 0;
			const size_t row_offset = y * bytes_per_row;
			for (size_t x = 0; x < bytes_per_row; ++x)
				value = value * 256 + glyph[row_offset + x];
			font.rows[size_t(c - first_char) * height + y] = uint16_t(value >> (bytes_per_row * 8 - width));
		}
	}
	return font;
}

void emit(const std::string& input, const std::string& output, const FontData& font)
{
	const std::string id = identifier(stem(output));
	const std::string name = stem(input);

	std::string out;
	out += "// This is a generated file, do not edit.\n";
	out += "// Generated by: generate_font " + input + " " + output + "\n";
	out += "// Font: " + name + ", chars 0x20-0x7F\n";
	out += "#include \"../draw.hh\"\n\n";
	out += "const uint16_t " + id + "_glyphs[" + std::to_string(glyph_count) + " * " + std::to_string(font.height) + "] = {\n";
	for (int c = first_char; c <= last_char; ++c)
	{
		char buf[32];
		snprintf(buf, sizeof(buf), "\t/* 0x%02X */\n", c);
		out += buf;
		const size_t base = size_t(c - first_char) * font.height;
		for (unsigned y = 0; y < font.height; ++y)
		{
			if (y % 8 == 0)
				out += "\t";
			else
				out += " ";
			out += hex16(font.rows[base + y]);
			out += ",";
			if (y % 8 == 7 || y == font.height - 1)
				out += "\n";
		}
	}
	out += "};\n\n";
	out += "const Font " + id + " = { " + std::to_string(font.width) + ", " + std::to_string(font.height) +
	       ", \"" + name + "\", " + id + "_glyphs };\n";

	write_file(output, out);
	printf("Generated %s successfully.\n", output.c_str());
	printf("Font:   %s (%u x %u)\n", name.c_str(), font.width, font.height);
	printf("Glyphs: %d (0x20-0x7F)\n", glyph_count);
}

} // namespace

int main(int argc, char** argv)
{
	if (argc != 3)
	{
		fprintf(stderr, "Generate a C file with a Font (draw.hh) instance from a PSF1/PSF2 console font.\n\n");
		fprintf(stderr, "Usage: %s input.psf output.c\n", argv[0]);
		return 1;
	}

	try
	{
		const std::vector<unsigned char> data = read_file(argv[1]);
		FontData font;
		if (data.size() >= 2 && data[0] == 0x36 && data[1] == 0x04)
			font = convert_psf1(data);
		else if (data.size() >= 4 && u32le(data.data()) == 0x864AB572u)
			font = convert_psf2(data);
		else
			throw std::invalid_argument("unsupported font format (expected PSF1 or PSF2)");
		emit(argv[1], argv[2], font);
	}
	catch (const std::invalid_argument& e)
	{
		fprintf(stderr, "generate_font: %s\n", e.what());
		return 1;
	}
	return 0;
}
